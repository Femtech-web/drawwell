import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const ROOT = join(process.cwd(), "fixtures/awards");

async function main() {
  const samples = [];
  for (const id of (await readdir(ROOT)).sort()) {
    const dir = join(ROOT, id);
    const meta = JSON.parse(await readFile(join(dir, "award.json"), "utf8"));
    const docNames = (await readdir(join(dir, "docs"))).filter((f) => f.endsWith(".txt")).sort();
    const documents = await Promise.all(
      docNames.map(async (f) => ({ id: f.replace(/\.txt$/, ""), text: (await readFile(join(dir, "docs", f), "utf8")).trimEnd() })),
    );
    samples.push({
      ...meta,
      budgetCsv: await readFile(join(dir, "budget.csv"), "utf8"),
      ledgerCsv: await readFile(join(dir, "ledger.csv"), "utf8"),
      documents,
    });
  }
  samples.sort((a, b) => a.order - b.order);
  const out = `// Generated by scripts/build/samples.ts from fixtures/awards. Do not edit.\nimport type { SampleSource } from "./types";\n\nexport const SAMPLE_SOURCES: SampleSource[] = ${JSON.stringify(samples, null, 2)};\n`;
  await writeFile(join(process.cwd(), "src/samples/data.generated.ts"), out);
  console.log(`bundled ${samples.length} samples`);
}

main();
