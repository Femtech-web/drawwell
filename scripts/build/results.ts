import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

async function readJson(dir: string) {
  try {
    const files = (await readdir(dir)).filter((f) => f.endsWith(".json")).sort();
    return Promise.all(files.map(async (f) => ({ file: `${dir}/${f}`, ...JSON.parse(await readFile(join(dir, f), "utf8")) })));
  } catch {
    return [];
  }
}

async function main() {
  const runs = await readJson("docs/results/benchmark");
  const latest = new Map<string, unknown>();
  for (const r of runs) latest.set(`${r.config}:${r.model}`, r);
  const smoke = (await readJson("docs/results")).filter((r) => r.file.includes("serv-smoke"));
  const out = `// Generated by scripts/build/results.ts from docs/results. Do not edit.\n/* eslint-disable */\nexport const BENCHMARK_RUNS: any[] = ${JSON.stringify([...latest.values()])};\nexport const ALL_RUN_FILES: string[] = ${JSON.stringify(runs.map((r) => r.file))};\nexport const SMOKE_RUNS: any[] = ${JSON.stringify(smoke)};\n`;
  await writeFile("src/results/data.generated.ts", out);
  console.log(`bundled ${latest.size} latest benchmark runs (${runs.length} total), ${smoke.length} smoke files`);
}

main();
